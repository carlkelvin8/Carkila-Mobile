begin;

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  category text not null default 'General',
  body text not null check (char_length(btrim(body)) between 3 and 2000),
  quote_requested boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);
create index if not exists community_posts_created_idx on public.community_posts(created_at desc);
alter table public.community_posts enable row level security;
grant select,insert,update,delete on public.community_posts to authenticated;
grant usage,select on sequence public.community_posts_id_seq to authenticated;
drop policy if exists community_posts_read on public.community_posts;
create policy community_posts_read on public.community_posts for select to authenticated using (true);
drop policy if exists community_posts_insert on public.community_posts;
create policy community_posts_insert on public.community_posts for insert to authenticated with check (author_id=auth.uid());
drop policy if exists community_posts_owner_write on public.community_posts;
create policy community_posts_owner_write on public.community_posts for update to authenticated using (author_id=auth.uid()) with check (author_id=auth.uid());
drop policy if exists community_posts_owner_delete on public.community_posts;
create policy community_posts_owner_delete on public.community_posts for delete to authenticated using (author_id=auth.uid());

create or replace function public.complete_conversation(p_conversation_id bigint)
returns public.conversations language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_row public.conversations;
begin
  if v_user is null then raise exception 'Authentication required' using errcode='42501'; end if;
  update public.conversations set completed_at=coalesce(completed_at,timezone('utc',now())),completed_by_id=coalesce(completed_by_id,v_user)
  where id=p_conversation_id and v_user in (buyer_id,vendor_id) returning * into v_row;
  if v_row.id is null then raise exception 'Conversation not found or not permitted' using errcode='42501'; end if;
  return v_row;
end $$;
revoke all on function public.complete_conversation(bigint) from public,anon;
grant execute on function public.complete_conversation(bigint) to authenticated;

create or replace function public.get_profile_contact(p_profile_id uuid)
returns table(mobile_number text,email text,website text) language sql stable security definer set search_path='' as $$
  select p.mobile_number,p.email,p.website from public.profiles p
  where p.id=p_profile_id and p.deleted_at is null and (
    auth.uid()=p.id or exists (
      select 1 from public.conversations c
      where (c.buyer_id=auth.uid() and c.vendor_id=p.id)
         or (c.vendor_id=auth.uid() and c.buyer_id=p.id)
    )
  );
$$;
revoke all on function public.get_profile_contact(uuid) from public,anon;
grant execute on function public.get_profile_contact(uuid) to authenticated;

commit;
