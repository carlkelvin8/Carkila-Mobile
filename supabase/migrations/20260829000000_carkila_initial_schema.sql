declare t text;
begin
  foreach t in array array[
    'locations','profiles','categories','subcategories','vehicle_brands','vehicle_types',
    'vehicles','vehicle_variants','photos','listings','favorites','conversations','messages',
    'notifications','reviews','review_photos','reports','user_reports','user_blocks','user_follows',
    'listing_likes','search_logs','admin_logs','transactions','listing_credit_packages',
    'listing_credit_purchases','listing_credit_usages','listing_credit_transactions','listing_daily_views'
  ] loop
    execute format(
      'create trigger %I before update on public.%I for each row execute procedure public.set_updated_at()',
      'set_' || t || '_updated_at',
      t
    );
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

